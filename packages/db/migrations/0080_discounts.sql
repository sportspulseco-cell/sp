-- Registration discounts (finance gap 1 and 2):
--   * discount_codes: a code a league or org admin makes for one season,
--     percent (basis points) or fixed amount, usage limit, valid dates,
--     optional divisions and prices. Stored upper case without spaces,
--     so the (season, code) unique index is case-blind.
--   * discount_code_redemptions: one row per registration that used a
--     code, taken in the pay transaction with the invoice and released
--     once when the registration is rejected or cancelled. usage_count on
--     the code moves only with these rows (guarded UPDATE, like tier seats).
--   * season_family_pricing: the season's family maximum and sibling
--     discount, applied on the server when a family's 2nd and later
--     registrations are priced.
-- New tables only; nothing existing changes. Generated by drizzle-kit
-- (the snapshot also caught up with 0029/0060/0061/0070 columns, which
-- are left out here because those migrations already created them).
-- Idempotent: CREATE ... IF NOT EXISTS and guarded constraints. RLS on,
-- anon and authenticated revoked: only the API (service role) reads them.

