// Staging-only browser acceptance using the synthetic player from the connected season run.
import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { chromium, expect } from "@playwright/test";
import { CFG, OUT, TARGET, SUPABASE_IP, sql, login, call } from "./lib.mjs";
if (TARGET !== "staging") throw new Error("Membership proof rehearsal is staging-only");
const { ids } = JSON.parse(readFileSync(`${OUT}/latest.json`, "utf8"));
const player = ids.players["Team Alpha"].find(p => p.rostered);
assert.ok(player, "Complete a connected season registration run first");
const password = `Play!${ids.tag}x9`;
const membershipId = "QAMEMBER01";
const expiry = "2027-08-31";
const checks = [];
const browser = await chromium.launch({ args: [`--host-resolver-rules=MAP *.supabase.co ${SUPABASE_IP}`] });
async function signedIn(app, email, credential) {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage(); page.setDefaultTimeout(90000);
  const base = app === "superadmin" ? "https://staging-superadmin.sportspulse.us" : CFG.apps[app];
  const url = new URL("/sign-in", base);
  url.searchParams.set("x-vercel-protection-bypass", CFG.bypass(app));
  url.searchParams.set("x-vercel-set-bypass-cookie", "true");
  await page.goto(url.toString());
  await page.locator("input[type=email]").fill(email);
  await page.locator("input[type=password]").fill(credential);
  await page.locator("button[type=submit]").click();
  await page.waitForURL(u => !u.pathname.startsWith("/sign-in"));
  return { context, page, base };
}
try {
  const token = await login(player.email, password);
  const p = await signedIn("player", player.email, password);
  await p.page.goto(`${p.base}/compliance`);
  await p.page.getByRole("button", { name: "Update USA Hockey ID" }).click();
  const form = p.page.getByRole("dialog");
  await form.locator("#usa-hockey-id").fill(membershipId);
  await form.getByRole("button", { name: "Submit", exact: true }).click();
  await expect(form.getByText(/ID saved as pending/)).toBeVisible();
  await p.page.keyboard.press("Escape");
  checks.push("Player enters membership ID; it remains pending.");
  const pdfPage = await browser.newPage();
  await pdfPage.setContent(`<h1>SportsPulse QA membership proof</h1><p>SYNTHETIC TEST DOCUMENT — NOT A REGISTRY CARD</p><p>Member: ${player.name}</p><p>Membership ID: ${membershipId}</p><p>Expires: ${expiry}</p>`);
  const pdf = await pdfPage.pdf({ format: "A4" }); await pdfPage.close();
  const options = await p.page.locator("#upload-target option").evaluateAll(rows => rows.map(r => ({ value: r.value, label: r.textContent })));
  const target = options.find(o => o.value && o.label.includes("Season 2026")); assert.ok(target);
  await p.page.locator("#upload-target").selectOption(target.value);
  await p.page.locator("#upload-kind").selectOption("governing_body_card");
  await p.page.locator("#upload-file").setInputFiles({ name: "QA-membership-proof.pdf", mimeType: "application/pdf", buffer: pdf });
  const uploadResponse = p.page.waitForResponse(r => r.request().method() === "POST" && r.url().endsWith("/compliance/self/documents/uploads"));
  await p.page.getByRole("button", { name: "Upload", exact: true }).click();
  const uploaded = await uploadResponse; assert.equal(uploaded.status(), 201);
  const { submission } = await uploaded.json(); assert.ok(submission.id);
  await expect(p.page.getByText(/Uploaded\. Status:/)).toBeVisible();
  checks.push("Player uploads proof to the season's private review queue.");
  const staff = await signedIn("superadmin", CFG.superAdmin.email, CFG.superAdmin.password);
  await staff.page.goto(`${staff.base}/eligibility`);
  const row = staff.page.getByRole("row").filter({ hasText: player.name }).filter({ hasText: /Governing|membership/i }).first();
  await row.getByRole("button", { name: "Review", exact: true }).click();
  const dialog = staff.page.getByRole("dialog");
  const fileLink = dialog.getByRole("link", { name: /Open the file/ });
  await expect(fileLink).toBeVisible();
  const file = await staff.page.request.get(await fileLink.getAttribute("href")); assert.equal(file.status(), 200);
  assert.ok((await file.body()).subarray(0, 5).equals(Buffer.from("%PDF-")));
  await dialog.locator("select").selectOption({ label: `USA Hockey · ${membershipId} (pending)` });
  await dialog.getByLabel("Membership expires on").fill(expiry);
  await dialog.getByRole("checkbox", { name: /I checked the card/ }).check();
  await staff.page.screenshot({ path: `${OUT}/membership-proof-review.png`, fullPage: true });
  const decisionResponse = staff.page.waitForResponse(r => r.request().method() === "POST" && r.url().endsWith(`/document-submissions/${submission.id}/decision`));
  await dialog.getByRole("button", { name: "Approve", exact: true }).click();
  const decision = await decisionResponse; assert.equal(decision.status(), 201);
  const accepted = await decision.json(); assert.equal(accepted.status, "approved");
  const [verified] = await sql`select status, source, expires_at, metadata->'manualReview' proof from identity_verifications where person_id=${submission.personId} and external_id=${membershipId}`;
  assert.equal(verified.status, "verified"); assert.equal(verified.source, "document_upload");
  assert.equal(verified.proof.submissionId, submission.id); assert.ok(verified.proof.reviewerUserId);
  checks.push("Staff reads private proof and records verified ID, expiry, reviewer and evidence provenance.");
  const changed = await call("POST", "/compliance/self/identity-verifications", { governingBodyCode: "USA_HOCKEY", externalId: "QAMEMBER02" }, token);
  assert.equal(changed.status, 201); assert.equal(changed.json.status, "pending");
  const [pending] = await sql`select status, verified_at, expires_at from identity_verifications where person_id=${submission.personId} and external_id='QAMEMBER02'`;
  assert.equal(pending.status, "pending"); assert.equal(pending.verified_at, null); assert.equal(pending.expires_at, null);
  checks.push("Changing the ID removes verification and returns it to pending.");
  console.log(checks.map(c => `PASS ${c}`).join("\n"));
  writeFileSync(`${OUT}/membership-proof-browser.json`, JSON.stringify({ tag: ids.tag, submissionId: submission.id, checks, passed: true }, null, 2));
} catch (error) {
  writeFileSync(`${OUT}/membership-proof-browser.json`, JSON.stringify({ tag: ids.tag, checks, passed: false, error: error.message }, null, 2));
  throw error;
} finally { await browser.close(); await sql.end(); }
